function FocusRing({
  size,
  className,
}: {
  size: number;
  className: string;
}) {
  const r = size / 2;
  return (
    <span className={className} aria-hidden="true">
      <svg viewBox={`0 0 ${size} ${size}`} width={size} height={size} fill="none">
        <rect
          x="0.5"
          y="0.5"
          width={size - 1}
          height={size - 1}
          rx={r}
          stroke="#91D59A"
          strokeWidth="1"
        />
        <circle cx={r} cy={r} r={size * 0.09} fill="#91D59A" />
      </svg>
    </span>
  );
}

